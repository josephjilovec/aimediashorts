"""
Base Social Media Bot Connector
Provides foundation for automated posting, metadata parsing, vocabulary sanitization, and dispatch tracking.
"""

import os
import sys
import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional
from datetime import datetime, timezone

from core import config
from core import vocabulary_guard

logger = logging.getLogger("BaseConnector")


class BaseSocialMediaConnector:
    """
    Abstract base connector for social media bots.
    Reads curated photos and 9:16 shorts from ALL_BOTS_MEDIA_INBOX,
    extracts AI-generated descriptions and tags, sanitizes content through Vocabulary Guard,
    and publishes to the target network.
    """

    def __init__(self, platform_name: str, dry_run: bool = False):
        self.platform_name = platform_name.lower().strip()
        self.dry_run = dry_run
        self.inbox_dir = config.ALL_BOTS_DIR
        self.dispatched_ledger_file = config.PACKAGE_ROOT / f"dispatched_{self.platform_name}.json"
        self.dispatched_ledger = self._load_ledger()

    def _load_ledger(self) -> Dict[str, Any]:
        if self.dispatched_ledger_file.exists():
            try:
                with open(self.dispatched_ledger_file, "r", encoding="utf-8") as f:
                    return json.load(f)
            except Exception as e:
                logger.warning(f"Failed loading dispatch ledger {self.dispatched_ledger_file}: {e}")
        return {"published": {}}

    def _save_ledger(self):
        try:
            with open(self.dispatched_ledger_file, "w", encoding="utf-8") as f:
                json.dump(self.dispatched_ledger, f, indent=2)
        except Exception as e:
            logger.error(f"Failed saving dispatch ledger: {e}")

    def is_already_published(self, media_path: Path) -> bool:
        return media_path.name in self.dispatched_ledger.get("published", {})

    def mark_published(self, media_path: Path, external_post_id: str = ""):
        self.dispatched_ledger.setdefault("published", {})[media_path.name] = {
            "published_at": datetime.now(timezone.utc).isoformat(),
            "external_id": external_post_id,
            "dry_run": self.dry_run,
        }
        self._save_ledger()

    def read_metadata_sidecar(self, media_path: Path) -> Dict[str, Any]:
        """Reads companion .json file generated by the auto shorts pipeline."""
        sidecar = media_path.with_suffix(media_path.suffix + ".json")
        if not sidecar.exists():
            # Try alternate naming: photo.jpg -> photo.json
            alt = media_path.with_suffix(".json")
            if alt.exists():
                sidecar = alt

        meta = {
            "title": media_path.stem.replace("_", " ").title(),
            "caption": "",
            "tags": ["#Shorts", "#Content", "#AI"],
            "summary": ""
        }

        if sidecar.exists():
            try:
                with open(sidecar, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    meta.update(data)
            except Exception as e:
                logger.warning(f"Could not read sidecar {sidecar.name}: {e}")

        # Strictly sanitize through Vocabulary Guard
        meta["title"] = vocabulary_guard.sanitize_social_text(meta.get("title", ""))
        meta["caption"] = vocabulary_guard.sanitize_social_text(meta.get("caption", ""))
        return meta

    def build_post_text(self, metadata: Dict[str, Any], max_len: int = 280) -> str:
        """Constructs safe, filtered social media post text."""
        caption = metadata.get("caption") or metadata.get("title", "")
        tags = " ".join(metadata.get("tags", []))
        
        full_text = f"{caption}\n\n{tags}".strip()
        safe_text = vocabulary_guard.sanitize_social_text(full_text)

        if len(safe_text) > max_len:
            safe_text = safe_text[: max_len - 3] + "..."
        return safe_text

    def post_image(self, image_path: Path, text: str) -> Optional[str]:
        """Publish an image to the platform. Override in subclass."""
        raise NotImplementedError

    def post_video(self, video_path: Path, text: str) -> Optional[str]:
        """Publish a 9:16 video short to the platform. Override in subclass."""
        raise NotImplementedError

    def publish_pending_queue(self, max_items: int = 5) -> List[Dict[str, Any]]:
        """
        Scans ALL_BOTS_MEDIA_INBOX, finds unposted media, and publishes each item.
        """
        results = []
        if not self.inbox_dir.exists():
            return results

        valid_exts = {".jpg", ".jpeg", ".png", ".webp", ".mp4", ".mov"}
        pending_files = [
            f for f in sorted(self.inbox_dir.iterdir())
            if f.is_file() and f.suffix.lower() in valid_exts and not self.is_already_published(f)
        ]

        logger.info(f"[{self.platform_name.upper()}] Found {len(pending_files)} pending media items in inbox.")

        for media_path in pending_files[:max_items]:
            meta = self.read_metadata_sidecar(media_path)
            post_text = self.build_post_text(meta)
            is_video = media_path.suffix.lower() in {".mp4", ".mov"}

            logger.info(f"[{self.platform_name.upper()}] Posting {'video' if is_video else 'photo'}: {media_path.name}")

            if self.dry_run:
                logger.info(f"  [DRY RUN] Would publish to {self.platform_name}: '{post_text}'")
                self.mark_published(media_path, external_post_id="DRY_RUN_ID")
                results.append({"status": "simulated", "file": media_path.name, "text": post_text})
                continue

            try:
                if is_video:
                    post_id = self.post_video(media_path, post_text)
                else:
                    post_id = self.post_image(media_path, post_text)

                if post_id:
                    self.mark_published(media_path, external_post_id=post_id)
                    logger.info(f"  [+] Published successfully! Post ID: {post_id}")
                    results.append({"status": "success", "file": media_path.name, "post_id": post_id})
                else:
                    logger.warning(f"  [-] Failed posting {media_path.name} to {self.platform_name}")
                    results.append({"status": "failed", "file": media_path.name})
            except Exception as e:
                logger.error(f"  [!] Exception posting {media_path.name} to {self.platform_name}: {e}")
                results.append({"status": "error", "file": media_path.name, "error": str(e)})

        return results
